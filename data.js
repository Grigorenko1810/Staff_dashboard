window.normalizeMockParticipants = function normalizeMockParticipants(sourceData = window.mockData) {
  const normalizeParticipants = (item) => {
    if (!item || !Object.prototype.hasOwnProperty.call(item, 'participants')) return;
    const toList = (value) => {
      if (Array.isArray(value)) return value;
      if (typeof value === 'string' && value.trim()) return [value.trim()];
      return [];
    };
    if (Array.isArray(item.participants)) {
      item.participants = {
        active: item.participants.slice(0, 1),
        all: item.participants.slice()
      };
      return;
    }
    if (typeof item.participants === 'string' && item.participants.trim()) {
      item.participants = {
        active: [item.participants.trim()],
        all: [item.participants.trim()]
      };
      return;
    }
    if (item.participants && typeof item.participants === 'object') {
      const active = toList(item.participants.active);
      const all = toList(item.participants.all);
      const normalizedAll = all.length ? all : active;
      const normalizedActive = active.length ? active : normalizedAll.slice(0, 1);
      item.participants = { active: normalizedActive, all: normalizedAll };
    }
  };

  (sourceData.tasks || []).forEach((task) => {
    if (!task.detailName && task.assignedDetails) {
      task.detailName = task.assignedDetails;
    }
    normalizeParticipants(task);
  });

  (sourceData.subtasks || []).forEach((subtask) => {
    if (!subtask.detailName && subtask.assignedDetails) {
      subtask.detailName = subtask.assignedDetails;
    }
    normalizeParticipants(subtask);
  });
};

window.normalizeMockParticipants();

window.ensureDynamicRawData = function ensureDynamicRawData(sourceData = window.mockData) {
  const data = sourceData;
  const currentYear = new Date().getFullYear();
  const dayMs = 24 * 60 * 60 * 1000;
  const clampLoad = (value) => Math.max(24, Math.min(98, Math.round(value)));
  const formatDate = (date) => {
    const pad = (value) => String(value).padStart(2, '0');
    return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
  };
  const createRawSeries = (baseValue, seed = 0) => {
    const startDate = new Date(currentYear, 0, 1);
    const endDate = new Date(currentYear, 11, 31);
    const values = [];

    for (let current = new Date(startDate), index = 0; current <= endDate; current = new Date(current.getTime() + dayMs), index += 1) {
      const monthTrend = current.getMonth() * 0.45;
      const weeklyWave = Math.sin((index + seed) / 6) * 4;
      const seasonalWave = Math.cos((index + seed * 3) / 27) * 3;
      values.push({
        date: formatDate(current),
        value: clampLoad(baseValue + monthTrend + weeklyWave + seasonalWave)
      });
    }

    return values;
  };

  const average = (items) => {
    const values = (items || []).map(Number).filter(Number.isFinite);
    return values.length ? values.reduce((sum, value) => sum + value, 0) / values.length : null;
  };

  const getSeriesAverage = (dynamicLoad) => {
    const monthValues = (dynamicLoad?.months || []).map((item) => Number(item.value ?? item));
    const weekValues = (dynamicLoad?.weeks || []).map((item) => Number(item.value ?? item));
    return average(monthValues) ?? average(weekValues) ?? 72;
  };

  if (data.dynamicLoad && !Array.isArray(data.dynamicLoad.raw)) {
    data.dynamicLoad.raw = createRawSeries(getSeriesAverage(data.dynamicLoad), 1);
  }

  (data.centers || []).forEach((center, index) => {
    center.dynamicLoad = center.dynamicLoad || {};
    if (!Array.isArray(center.dynamicLoad.raw)) {
      center.dynamicLoad.raw = createRawSeries(getSeriesAverage(center.dynamicLoad), index + 2);
    }
  });

  (data.employees || []).forEach((employee, index) => {
    const baseValue = Number(employee.loadPercent) || getSeriesAverage(employee.dynamicLoad) || 72;
    employee.history = employee.history || {};
    employee.dynamicLoad = employee.dynamicLoad || {};
    if (!Array.isArray(employee.history.raw)) {
      employee.history.raw = createRawSeries(baseValue, index + 11);
    }
    if (!Array.isArray(employee.dynamicLoad.raw)) {
      employee.dynamicLoad.raw = employee.history.raw;
    }
  });
};

window.ensureDynamicRawData();
